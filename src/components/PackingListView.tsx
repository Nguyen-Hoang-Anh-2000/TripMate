import React, { useState, useRef, useEffect, useMemo } from 'react';
import {
  CheckCircle2,
  Circle,
  Plus,
  Sparkles,
  Package,
  Trash2,
  Edit3,
  X,
  Check,
  Search,
  ChevronDown,
  Settings2,
  CheckSquare,
  Square
} from 'lucide-react';
import { Trip, PackingItem } from '../types';
import { useLanguage } from '../context/LanguageContext';
import {
  PackingCategoryConfig,
  getSavedPackingCategories,
  PackingCategorySettingsModal
} from './PackingCategorySettingsModal';

interface PackingListViewProps {
  trip: Trip;
  onToggleItem: (itemId: string) => void;
  onAddItem: (item: Omit<PackingItem, 'id' | 'isPacked'>) => void;
  onEditItem: (itemId: string, updated: Partial<PackingItem>) => void;
  onDeleteItem: (itemId: string) => void;
  onGenerateAiPackingList: () => void;
  isAiLoading: boolean;
}

export const PackingListView: React.FC<PackingListViewProps> = ({
  trip,
  onToggleItem,
  onAddItem,
  onEditItem,
  onDeleteItem,
  onGenerateAiPackingList,
  isAiLoading,
}) => {
  const { lang } = useLanguage();
  const isVi = lang === 'vi';

  // Configured packing categories state
  const [categories, setCategories] = useState<PackingCategoryConfig[]>(() => getSavedPackingCategories());
  const [isCategoryModalOpen, setIsCategoryModalOpen] = useState(false);

  // Helper to determine which categories have items in the packing list
  const getCategoriesWithItems = (items: PackingItem[], allCats: PackingCategoryConfig[]) => {
    const idsWithItems = Array.from(new Set(items.map((i) => i.category))).filter((id) =>
      allCats.some((c) => c.id === id)
    );
    return idsWithItems.length > 0 ? idsWithItems : allCats.map((c) => c.id);
  };

  // Multi-checkbox combobox category filter state: default to categories that have items added
  const [selectedCategoryIds, setSelectedCategoryIds] = useState<string[]>(() =>
    getCategoriesWithItems(trip.packingList, getSavedPackingCategories())
  );
  const [isCategoryDropdownOpen, setIsCategoryDropdownOpen] = useState(false);
  const [categorySearchQuery, setCategorySearchQuery] = useState('');
  const categoryDropdownRef = useRef<HTMLDivElement>(null);

  // Status filter: 'all' | 'unpacked' | 'packed'
  const [statusFilter, setStatusFilter] = useState<'all' | 'unpacked' | 'packed'>('all');

  // Modals state
  const [isAddModalOpen, setIsAddModalOpen] = useState(false);
  const [newItemName, setNewItemName] = useState('');
  const [newItemCategory, setNewItemCategory] = useState<string>('Essentials');
  const [newItemQty, setNewItemQty] = useState(1);

  // Edit item state
  const [editingItem, setEditingItem] = useState<PackingItem | null>(null);
  const [editName, setEditName] = useState('');
  const [editCategory, setEditCategory] = useState<string>('Essentials');
  const [editQty, setEditQty] = useState(1);
  const [editPacked, setEditPacked] = useState(false);

  // Delete item confirmation modal
  const [itemToDelete, setItemToDelete] = useState<PackingItem | null>(null);

  // Close category combobox on click outside
  useEffect(() => {
    const handleClickOutside = (event: MouseEvent) => {
      if (
        categoryDropdownRef.current &&
        !categoryDropdownRef.current.contains(event.target as Node)
      ) {
        setIsCategoryDropdownOpen(false);
      }
    };
    document.addEventListener('mousedown', handleClickOutside);
    return () => document.removeEventListener('mousedown', handleClickOutside);
  }, []);

  // Sync selected categories when active trip changes
  useEffect(() => {
    setSelectedCategoryIds(getCategoriesWithItems(trip.packingList, categories));
  }, [trip.id]);

  // When items are generated by AI, auto-select categories that have items
  const prevItemsLengthRef = useRef(trip.packingList.length);
  useEffect(() => {
    if (prevItemsLengthRef.current === 0 && trip.packingList.length > 0) {
      setSelectedCategoryIds(getCategoriesWithItems(trip.packingList, categories));
    }
    prevItemsLengthRef.current = trip.packingList.length;
  }, [trip.packingList.length, categories]);

  // Sync selected categories if a category was deleted
  useEffect(() => {
    const existingIds = categories.map((c) => c.id);
    setSelectedCategoryIds((prev) => {
      const valid = prev.filter((id) => existingIds.includes(id));
      return valid.length > 0 ? valid : existingIds;
    });
  }, [categories]);

  const getCategoryName = (catId: string) => {
    const found = categories.find((c) => c.id === catId);
    if (!found) return catId;
    return isVi ? found.nameVi : found.nameEn;
  };

  const getCategoryIcon = (catId: string) => {
    const found = categories.find((c) => c.id === catId);
    return found?.icon || '📦';
  };

  // Toggle category checkbox in combobox
  const handleToggleCategoryCheckbox = (catId: string) => {
    if (selectedCategoryIds.includes(catId)) {
      if (selectedCategoryIds.length === 1) return; // Keep at least one
      setSelectedCategoryIds(selectedCategoryIds.filter((id) => id !== catId));
    } else {
      setSelectedCategoryIds([...selectedCategoryIds, catId]);
    }
  };

  const handleSelectAllCategories = () => {
    if (selectedCategoryIds.length === categories.length) {
      setSelectedCategoryIds([categories[0]?.id || 'Essentials']);
    } else {
      setSelectedCategoryIds(categories.map((c) => c.id));
    }
  };

  // Add Item Submit
  const handleOpenAddModal = () => {
    setNewItemName('');
    setNewItemCategory(categories[0]?.id || 'Essentials');
    setNewItemQty(1);
    setIsAddModalOpen(true);
  };

  const handleSaveNewItem = (e: React.FormEvent) => {
    e.preventDefault();
    if (!newItemName.trim()) return;

    onAddItem({
      name: newItemName.trim(),
      category: newItemCategory,
      quantity: newItemQty || 1,
    });

    // Ensure newly added item's category is checked so it is immediately visible
    setSelectedCategoryIds((prev) =>
      prev.includes(newItemCategory) ? prev : [...prev, newItemCategory]
    );

    setIsAddModalOpen(false);
    setNewItemName('');
    setNewItemQty(1);
  };

  // Edit Item Handlers
  const handleOpenEditModal = (item: PackingItem) => {
    setEditingItem(item);
    setEditName(item.name);
    setEditCategory(item.category);
    setEditQty(item.quantity || 1);
    setEditPacked(!!item.isPacked);
  };

  const handleSaveEditItem = (e: React.FormEvent) => {
    e.preventDefault();
    if (!editingItem || !editName.trim()) return;

    onEditItem(editingItem.id, {
      name: editName.trim(),
      category: editCategory,
      quantity: editQty || 1,
      isPacked: editPacked,
    });

    setEditingItem(null);
  };

  const handleConfirmDelete = () => {
    if (itemToDelete) {
      onDeleteItem(itemToDelete.id);
      setItemToDelete(null);
    }
  };

  // Filter items
  const filteredCategories = useMemo(() => {
    return categories.filter((c) => selectedCategoryIds.includes(c.id));
  }, [categories, selectedCategoryIds]);

  const packedCount = trip.packingList.filter((i) => i.isPacked).length;
  const totalCount = trip.packingList.length;

  return (
    <div className="space-y-4">
      {/* Top Action Bar */}
      <div className="bg-white rounded-2xl p-3 sm:p-4 border border-slate-200/90 shadow-2xs space-y-3">
        {/* Row 1: Nút gợi ý AI nằm trên bên trái, nút thêm nằm bên phải kế bên */}
        <div className="flex items-center justify-between gap-2">
          {/* Nút gợi ý AI nằm trên bên trái */}
          <button
            type="button"
            onClick={onGenerateAiPackingList}
            disabled={isAiLoading}
            className="px-3.5 py-2 bg-gradient-to-r from-teal-600 to-emerald-600 hover:from-teal-700 hover:to-emerald-700 text-white font-semibold text-xs rounded-xl shadow-xs transition-all flex items-center gap-1.5 cursor-pointer disabled:opacity-50 min-h-[38px]"
            title={isVi ? 'Gợi ý danh mục đồ đạc bằng AI' : 'Generate packing list with AI'}
          >
            <Sparkles className={`w-3.5 h-3.5 text-amber-200 shrink-0 ${isAiLoading ? 'animate-spin' : ''}`} />
            <span className="whitespace-nowrap">
              {isAiLoading
                ? (isVi ? 'Đang tạo...' : 'Generating...')
                : (isVi ? 'Gợi ý AI' : 'AI Suggestions')}
            </span>
          </button>

          {/* Nút thêm đồ nằm bên phải kế bên */}
          <button
            type="button"
            onClick={handleOpenAddModal}
            className="px-4 py-2 bg-teal-600 hover:bg-teal-700 text-white font-semibold text-xs rounded-xl shadow-xs transition-colors flex items-center gap-1.5 cursor-pointer min-h-[38px]"
          >
            <Plus className="w-4 h-4 shrink-0" />
            <span className="whitespace-nowrap">{isVi ? 'Thêm đồ' : 'Add Item'}</span>
          </button>
        </div>

        {/* Row 2: Combobox phân loại nằm dưới nút gợi ý và thêm đồ + Bộ lọc trạng thái */}
        <div className="flex flex-col sm:flex-row items-stretch sm:items-center justify-between gap-2.5">
          {/* Combobox phân loại (Nút cấu hình nằm bên trong combobox) */}
          <div className="relative flex-1 min-w-0 sm:max-w-xs" ref={categoryDropdownRef}>
            <button
              type="button"
              onClick={() => setIsCategoryDropdownOpen(!isCategoryDropdownOpen)}
              className={`w-full flex items-center justify-between gap-2 text-xs font-semibold py-2 px-3 rounded-xl border transition-colors shadow-2xs cursor-pointer ${
                selectedCategoryIds.length < categories.length
                  ? 'border-teal-500 bg-teal-50/80 text-teal-900 font-bold'
                  : 'border-slate-200 bg-white text-slate-800 hover:bg-slate-50'
              }`}
            >
              <div className="flex items-center gap-1.5 min-w-0 truncate">
                <span className="text-teal-600 shrink-0">🏷️</span>
                <span className="truncate">
                  {selectedCategoryIds.length === categories.length
                    ? (isVi ? 'Tất cả phân loại' : 'All Categories')
                    : (isVi ? `${selectedCategoryIds.length} phân loại đã chọn` : `${selectedCategoryIds.length} categories`)}
                </span>
              </div>
              <ChevronDown
                className={`w-3.5 h-3.5 text-slate-400 shrink-0 transition-transform ${
                  isCategoryDropdownOpen ? 'rotate-180' : ''
                }`}
              />
            </button>

            {/* Combobox Multicheckbox Popover Menu */}
            {isCategoryDropdownOpen && (
              <div className="absolute left-0 top-full mt-1.5 w-80 max-w-[calc(100vw-2rem)] bg-white rounded-2xl border border-slate-200 shadow-xl z-50 p-2.5 space-y-2 animate-in fade-in zoom-in-95 duration-100">
                {/* Search inside combobox */}
                <div className="relative">
                  <Search className="w-3.5 h-3.5 text-slate-400 absolute left-2.5 top-1/2 -translate-y-1/2 pointer-events-none" />
                  <input
                    type="text"
                    autoFocus
                    value={categorySearchQuery}
                    onChange={(e) => setCategorySearchQuery(e.target.value)}
                    placeholder={isVi ? 'Tìm phân loại...' : 'Search categories...'}
                    className="w-full text-xs pl-8 pr-3 py-1.5 rounded-lg border border-slate-200 bg-slate-50 focus:bg-white text-slate-800 focus:outline-hidden focus:ring-1 focus:ring-teal-500"
                  />
                </div>

                {/* Header: Phân loại đồ + Nút Cấu hình phía trên gần tiêu đề + Chọn tất cả */}
                <div className="flex items-center justify-between px-1 py-1 border-b border-slate-100 gap-2">
                  <span className="text-[11px] font-bold text-slate-500 uppercase tracking-wider">
                    {isVi ? 'Phân loại đồ' : 'Categories'}
                  </span>
                  <div className="flex items-center gap-1.5">
                    {/* Nút Cấu hình phía trên gần tiêu đề */}
                    <button
                      type="button"
                      onClick={() => {
                        setIsCategoryDropdownOpen(false);
                        setIsCategoryModalOpen(true);
                      }}
                      className="text-[11px] font-semibold text-slate-600 hover:text-teal-700 flex items-center gap-1 px-2 py-0.5 rounded-lg hover:bg-slate-100 transition-colors cursor-pointer border border-slate-200/80 bg-slate-50/60"
                      title={isVi ? 'Cấu hình phân loại' : 'Configure Categories'}
                    >
                      <Settings2 className="w-3 h-3 text-slate-500" />
                      <span>{isVi ? 'Cấu hình' : 'Config'}</span>
                    </button>

                    <span className="text-slate-200">|</span>

                    {/* Select / Deselect All Action */}
                    <button
                      type="button"
                      onClick={handleSelectAllCategories}
                      className="text-[11px] font-semibold text-teal-600 hover:text-teal-800 cursor-pointer px-1 py-0.5"
                    >
                      {selectedCategoryIds.length === categories.length
                        ? (isVi ? 'Bỏ chọn' : 'Deselect all')
                        : (isVi ? 'Chọn tất cả' : 'Select all')}
                    </button>
                  </div>
                </div>

                {/* Category options list with checkboxes */}
                <div className="max-h-56 overflow-y-auto space-y-1 pr-0.5">
                  {categories
                    .filter((c) => {
                      const name = isVi ? c.nameVi : c.nameEn;
                      return name.toLowerCase().includes(categorySearchQuery.toLowerCase());
                    })
                    .map((cat) => {
                      const isChecked = selectedCategoryIds.includes(cat.id);
                      const count = trip.packingList.filter((i) => i.category === cat.id).length;

                      return (
                        <div
                          key={cat.id}
                          onClick={() => handleToggleCategoryCheckbox(cat.id)}
                          className={`flex items-center justify-between p-2 rounded-xl text-xs font-medium cursor-pointer transition-colors ${
                            isChecked
                              ? 'bg-teal-50/80 text-teal-950 font-bold border border-teal-200/60'
                              : 'hover:bg-slate-50 text-slate-700 border border-transparent'
                          }`}
                        >
                          <div className="flex items-center gap-2 min-w-0 flex-1">
                            <div className="shrink-0">
                              {isChecked ? (
                                <CheckSquare className="w-4 h-4 text-teal-600" />
                              ) : (
                                <Square className="w-4 h-4 text-slate-300" />
                              )}
                            </div>
                            <span className="shrink-0">{cat.icon}</span>
                            <span className="truncate">{isVi ? cat.nameVi : cat.nameEn}</span>
                          </div>
                          <span className="text-[11px] text-slate-400 font-semibold shrink-0 ml-1">
                            ({count})
                          </span>
                        </div>
                      );
                    })}
                </div>
              </div>
            )}
          </div>

          {/* Bộ lọc trạng thái */}
          <div className="grid grid-cols-3 sm:flex items-center gap-1 bg-slate-100/90 p-1 rounded-xl border border-slate-200/60 text-xs text-center font-medium shrink-0">
            <button
              type="button"
              onClick={() => setStatusFilter('all')}
              className={`py-1.5 px-2.5 sm:px-3 rounded-lg font-semibold transition-all cursor-pointer truncate ${
                statusFilter === 'all'
                  ? 'bg-white text-slate-900 shadow-2xs font-bold'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              {isVi ? 'Tất cả' : 'All'} ({totalCount})
            </button>
            <button
              type="button"
              onClick={() => setStatusFilter('unpacked')}
              className={`py-1.5 px-2.5 sm:px-3 rounded-lg font-semibold transition-all cursor-pointer truncate ${
                statusFilter === 'unpacked'
                  ? 'bg-white text-amber-900 shadow-2xs font-bold'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              {isVi ? 'Chưa chuẩn bị' : 'Unpacked'} ({totalCount - packedCount})
            </button>
            <button
              type="button"
              onClick={() => setStatusFilter('packed')}
              className={`py-1.5 px-2.5 sm:px-3 rounded-lg font-semibold transition-all cursor-pointer truncate ${
                statusFilter === 'packed'
                  ? 'bg-white text-emerald-900 shadow-2xs font-bold'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              {isVi ? 'Đã chuẩn bị' : 'Packed'} ({packedCount})
            </button>
          </div>
        </div>
      </div>

      {/* Categorized Checklist View */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-3.5">
        {filteredCategories.map((cat) => {
          let itemsInCat = trip.packingList.filter((i) => i.category === cat.id);
          if (statusFilter === 'packed') itemsInCat = itemsInCat.filter((i) => i.isPacked);
          if (statusFilter === 'unpacked') itemsInCat = itemsInCat.filter((i) => !i.isPacked);

          const catPackedCount = trip.packingList.filter((i) => i.category === cat.id && i.isPacked).length;
          const catTotalCount = trip.packingList.filter((i) => i.category === cat.id).length;

          // If filtering and no items match in this category
          if (itemsInCat.length === 0 && statusFilter !== 'all') {
            return null;
          }

          return (
            <div
              key={cat.id}
              className="bg-white p-4 rounded-2xl border border-slate-200/90 shadow-2xs flex flex-col justify-between"
            >
              <div>
                {/* Category Card Header */}
                <div className="flex items-center justify-between pb-2.5 mb-2.5 border-b border-slate-100">
                  <h4 className="font-display font-bold text-slate-900 text-sm flex items-center gap-2">
                    <span className="text-base">{cat.icon}</span>
                    <span>{isVi ? cat.nameVi : cat.nameEn}</span>
                  </h4>
                  <span className="text-[10px] font-bold text-slate-600 bg-slate-100 px-2 py-0.5 rounded-full">
                    {catPackedCount}/{catTotalCount} {isVi ? 'món' : 'items'}
                  </span>
                </div>

                {/* Items in Category */}
                {itemsInCat.length === 0 ? (
                  <div className="py-4 text-center">
                    <p className="text-xs text-slate-400 italic">
                      {isVi ? 'Chưa có món nào trong phân loại này.' : 'No items in this category.'}
                    </p>
                  </div>
                ) : (
                  <div className="space-y-1.5">
                    {itemsInCat.map((item) => (
                      <div
                        key={item.id}
                        className={`p-2.5 rounded-xl border transition-all flex items-center justify-between gap-2 ${
                          item.isPacked
                            ? 'bg-slate-50/70 border-slate-200/60 opacity-65'
                            : 'bg-white border-slate-200/80 hover:border-slate-300 shadow-2xs'
                        }`}
                      >
                        {/* Toggle Checkbox & Name */}
                        <button
                          type="button"
                          onClick={() => onToggleItem(item.id)}
                          className="flex items-center gap-2.5 text-left flex-1 min-w-0 cursor-pointer"
                        >
                          {item.isPacked ? (
                            <CheckCircle2 className="w-4 h-4 text-teal-600 shrink-0" />
                          ) : (
                            <Circle className="w-4 h-4 text-slate-300 hover:text-slate-400 shrink-0" />
                          )}
                          <span
                            className={`text-xs font-semibold truncate ${
                              item.isPacked ? 'line-through text-slate-400' : 'text-slate-800'
                            }`}
                          >
                            {item.name}
                          </span>
                          {item.quantity > 1 && (
                            <span className="text-[10px] font-bold text-slate-500 bg-slate-100 px-1.5 py-0.2 rounded-md shrink-0">
                              x{item.quantity}
                            </span>
                          )}
                        </button>

                        {/* Action buttons: Edit & Delete always horizontally side by side */}
                        <div className="flex items-center gap-1 shrink-0">
                          <button
                            type="button"
                            onClick={() => handleOpenEditModal(item)}
                            className="p-1 text-slate-400 hover:text-teal-600 hover:bg-teal-50 rounded-lg transition-colors cursor-pointer"
                            title={isVi ? 'Sửa món đồ' : 'Edit item'}
                          >
                            <Edit3 className="w-3.5 h-3.5" />
                          </button>
                          <button
                            type="button"
                            onClick={() => setItemToDelete(item)}
                            className="p-1 text-slate-400 hover:text-red-600 hover:bg-red-50 rounded-lg transition-colors cursor-pointer"
                            title={isVi ? 'Xóa món đồ' : 'Delete item'}
                          >
                            <Trash2 className="w-3.5 h-3.5" />
                          </button>
                        </div>
                      </div>
                    ))}
                  </div>
                )}
              </div>
            </div>
          );
        })}
      </div>

      {/* Empty State when no categories match */}
      {filteredCategories.length === 0 && (
        <div className="col-span-full text-center py-12 px-4 bg-white rounded-2xl border border-slate-200/80 shadow-2xs">
          <Package className="w-10 h-10 text-slate-300 mx-auto mb-2.5" />
          <p className="text-sm font-bold text-slate-700">
            {isVi ? 'Chưa chọn phân loại nào' : 'No categories selected'}
          </p>
          <p className="text-xs text-slate-400 mt-1 max-w-sm mx-auto">
            {isVi
              ? 'Hãy mở danh mục lọc phân loại ở trên để chọn xem các món đồ cần chuẩn bị.'
              : 'Please select one or more categories in the dropdown above to view items.'}
          </p>
          <button
            type="button"
            onClick={handleSelectAllCategories}
            className="mt-3.5 px-4 py-2 bg-teal-600 hover:bg-teal-700 text-white font-semibold text-xs rounded-xl shadow-xs transition-colors cursor-pointer"
          >
            {isVi ? 'Chọn tất cả phân loại' : 'Select All Categories'}
          </button>
        </div>
      )}

      {/* Popup Modal: Thêm đồ mới */}
      {isAddModalOpen && (
        <div className="fixed inset-0 z-50 bg-black/60 backdrop-blur-xs flex items-center justify-center p-3 sm:p-4 overflow-y-auto animate-in fade-in duration-150">
          <div
            className="bg-white rounded-2xl border border-slate-200 shadow-2xl w-full max-w-md p-5 space-y-4 my-auto"
            onClick={(e) => e.stopPropagation()}
          >
            {/* Header */}
            <div className="flex items-center justify-between pb-3 border-b border-slate-100">
              <h3 className="font-bold text-slate-900 text-sm sm:text-base flex items-center gap-2">
                <Plus className="w-4 h-4 text-teal-600" />
                <span>{isVi ? 'Thêm món đồ mới' : 'Add New Item'}</span>
              </h3>
              <button
                type="button"
                onClick={() => setIsAddModalOpen(false)}
                className="p-1.5 text-slate-400 hover:text-slate-600 rounded-lg hover:bg-slate-100 cursor-pointer"
              >
                <X className="w-4 h-4" />
              </button>
            </div>

            {/* Form */}
            <form onSubmit={handleSaveNewItem} className="space-y-3.5">
              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  {isVi ? 'Tên món đồ' : 'Item Name'} <span className="text-red-500">*</span>
                </label>
                <input
                  type="text"
                  required
                  autoFocus
                  placeholder={
                    isVi
                      ? 'Ví dụ: Sạc dự phòng, Áo khoác ấm, Hộ chiếu, Kem chống nắng...'
                      : 'e.g. Power bank, Warm jacket, Passport, Sunscreen...'
                  }
                  value={newItemName}
                  onChange={(e) => setNewItemName(e.target.value)}
                  className="w-full text-xs p-2.5 rounded-xl border border-slate-200 focus:ring-2 focus:ring-teal-500 focus:outline-hidden"
                />
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block text-xs font-semibold text-slate-700 mb-1">
                    {isVi ? 'Phân loại' : 'Category'}
                  </label>
                  <select
                    value={newItemCategory}
                    onChange={(e) => setNewItemCategory(e.target.value)}
                    className="w-full text-xs p-2.5 rounded-xl border border-slate-200 bg-white focus:ring-2 focus:ring-teal-500 focus:outline-hidden cursor-pointer"
                  >
                    {categories.map((c) => (
                      <option key={c.id} value={c.id}>
                        {c.icon} {isVi ? c.nameVi : c.nameEn}
                      </option>
                    ))}
                  </select>
                </div>

                <div>
                  <label className="block text-xs font-semibold text-slate-700 mb-1">
                    {isVi ? 'Số lượng' : 'Quantity'}
                  </label>
                  <input
                    type="number"
                    min="1"
                    value={newItemQty}
                    onChange={(e) => setNewItemQty(Math.max(1, parseInt(e.target.value, 10) || 1))}
                    className="w-full text-xs p-2.5 rounded-xl border border-slate-200 focus:ring-2 focus:ring-teal-500 focus:outline-hidden"
                  />
                </div>
              </div>

              {/* Buttons */}
              <div className="flex justify-end gap-2 pt-3 border-t border-slate-100">
                <button
                  type="button"
                  onClick={() => setIsAddModalOpen(false)}
                  className="px-4 py-2 text-xs font-semibold text-slate-600 hover:bg-slate-100 rounded-xl transition-colors cursor-pointer"
                >
                  {isVi ? 'Hủy' : 'Cancel'}
                </button>
                <button
                  type="submit"
                  className="px-5 py-2 text-xs font-bold text-white bg-teal-600 hover:bg-teal-700 rounded-xl shadow-xs transition-colors cursor-pointer"
                >
                  {isVi ? 'Lưu' : 'Save'}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

      {/* Popup Modal: Sửa món đồ */}
      {editingItem && (
        <div className="fixed inset-0 z-50 bg-black/60 backdrop-blur-xs flex items-center justify-center p-3 sm:p-4 overflow-y-auto animate-in fade-in duration-150">
          <div
            className="bg-white rounded-2xl border border-slate-200 shadow-2xl w-full max-w-md p-5 space-y-4 my-auto"
            onClick={(e) => e.stopPropagation()}
          >
            {/* Header */}
            <div className="flex items-center justify-between pb-3 border-b border-slate-100">
              <h3 className="font-bold text-slate-900 text-sm sm:text-base flex items-center gap-2">
                <Edit3 className="w-4 h-4 text-teal-600" />
                <span>{isVi ? 'Sửa món đồ' : 'Edit Item'}</span>
              </h3>
              <button
                type="button"
                onClick={() => setEditingItem(null)}
                className="p-1.5 text-slate-400 hover:text-slate-600 rounded-lg hover:bg-slate-100 cursor-pointer"
              >
                <X className="w-4 h-4" />
              </button>
            </div>

            {/* Form */}
            <form onSubmit={handleSaveEditItem} className="space-y-3.5">
              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  {isVi ? 'Tên món đồ' : 'Item Name'} <span className="text-red-500">*</span>
                </label>
                <input
                  type="text"
                  required
                  autoFocus
                  value={editName}
                  onChange={(e) => setEditName(e.target.value)}
                  className="w-full text-xs p-2.5 rounded-xl border border-slate-200 focus:ring-2 focus:ring-teal-500 focus:outline-hidden"
                />
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block text-xs font-semibold text-slate-700 mb-1">
                    {isVi ? 'Phân loại' : 'Category'}
                  </label>
                  <select
                    value={editCategory}
                    onChange={(e) => setEditCategory(e.target.value)}
                    className="w-full text-xs p-2.5 rounded-xl border border-slate-200 bg-white focus:ring-2 focus:ring-teal-500 focus:outline-hidden cursor-pointer"
                  >
                    {categories.map((c) => (
                      <option key={c.id} value={c.id}>
                        {c.icon} {isVi ? c.nameVi : c.nameEn}
                      </option>
                    ))}
                  </select>
                </div>

                <div>
                  <label className="block text-xs font-semibold text-slate-700 mb-1">
                    {isVi ? 'Số lượng' : 'Quantity'}
                  </label>
                  <input
                    type="number"
                    min="1"
                    value={editQty}
                    onChange={(e) => setEditQty(Math.max(1, parseInt(e.target.value, 10) || 1))}
                    className="w-full text-xs p-2.5 rounded-xl border border-slate-200 focus:ring-2 focus:ring-teal-500 focus:outline-hidden"
                  />
                </div>
              </div>

              {/* Status toggle */}
              <div className="pt-1">
                <label className="flex items-center gap-2.5 p-2.5 rounded-xl border border-slate-200 bg-slate-50/60 cursor-pointer hover:bg-slate-50">
                  <input
                    type="checkbox"
                    checked={editPacked}
                    onChange={(e) => setEditPacked(e.target.checked)}
                    className="w-4 h-4 rounded text-teal-600 focus:ring-teal-500 cursor-pointer"
                  />
                  <span className="text-xs font-semibold text-slate-800">
                    {isVi ? 'Đã chuẩn bị xong món này' : 'Mark as packed'}
                  </span>
                </label>
              </div>

              {/* Buttons */}
              <div className="flex justify-end gap-2 pt-3 border-t border-slate-100">
                <button
                  type="button"
                  onClick={() => setEditingItem(null)}
                  className="px-4 py-2 text-xs font-semibold text-slate-600 hover:bg-slate-100 rounded-xl transition-colors cursor-pointer"
                >
                  {isVi ? 'Hủy' : 'Cancel'}
                </button>
                <button
                  type="submit"
                  className="px-5 py-2 text-xs font-bold text-white bg-teal-600 hover:bg-teal-700 rounded-xl shadow-xs transition-colors cursor-pointer"
                >
                  {isVi ? 'Lưu' : 'Save'}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

      {/* Delete Item Confirmation Modal */}
      {itemToDelete && (
        <div className="fixed inset-0 z-50 bg-black/60 backdrop-blur-xs flex items-center justify-center p-4 animate-in fade-in duration-150">
          <div
            className="bg-white rounded-2xl border border-slate-200 shadow-2xl w-full max-w-sm p-5 space-y-4 text-center my-auto"
            onClick={(e) => e.stopPropagation()}
          >
            <div className="w-12 h-12 rounded-full bg-red-50 text-red-600 flex items-center justify-center mx-auto">
              <Trash2 className="w-6 h-6" />
            </div>
            <div>
              <h4 className="font-bold text-slate-900 text-sm sm:text-base">
                {isVi ? 'Xác nhận xóa món đồ?' : 'Delete Item?'}
              </h4>
              <p className="text-xs text-slate-500 mt-1.5 leading-relaxed">
                {isVi
                  ? `Bạn có chắc chắn muốn xóa "${itemToDelete.name}" khỏi danh mục đồ chuẩn bị?`
                  : `Are you sure you want to delete "${itemToDelete.name}"?`}
              </p>
            </div>

            <div className="flex gap-2.5 pt-1">
              <button
                type="button"
                onClick={() => setItemToDelete(null)}
                className="flex-1 px-4 py-2.5 text-xs font-semibold text-slate-700 bg-slate-100 hover:bg-slate-200 rounded-xl transition-colors cursor-pointer"
              >
                {isVi ? 'Hủy' : 'Cancel'}
              </button>
              <button
                type="button"
                onClick={handleConfirmDelete}
                className="flex-1 px-4 py-2.5 text-xs font-bold text-white bg-red-600 hover:bg-red-700 rounded-xl transition-colors cursor-pointer shadow-xs"
              >
                {isVi ? 'Xác nhận' : 'Confirm'}
              </button>
            </div>
          </div>
        </div>
      )}

      {/* Cấu hình phân loại Modal */}
      <PackingCategorySettingsModal
        isOpen={isCategoryModalOpen}
        onClose={() => setIsCategoryModalOpen(false)}
        categories={categories}
        onUpdateCategories={(newCats) => setCategories(newCats)}
      />
    </div>
  );
};
